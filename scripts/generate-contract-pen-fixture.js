//#region the contract-pen agreement fixture
// Regenerates test/consumer/linq-contract-generated.ts from the
// contract-pen corpus: `toTypeScript`'s declarations for every entry's
// EMITTED document (the pen builds it; nothing here is hand-written),
// one namespace per entry so three contracts can name `Operations`,
// `Client` and `Meta` in one file without colliding.
//
// The fixture is committed because the TYPE half of the agreement runs
// under `npm run test:types`, which type-checks files on disk;
// test/linq/contract-pen.test.js fails if this file drifts from what
// the generator produces, so the committed copy can never become stale
// evidence.
import * as fs from 'fs';
import * as path from 'path';

import { compileContract } from '@jarenjs/contract';
import { toTypeScript } from '@jarenjs/contract/project';

import { CORPUS } from '../test/linq/contract-corpus.js';

const ROOT = path.resolve(import.meta.dirname, '..');
export const HEADER = '// Generated by @jarenjs/contract\'s TypeScript projection from\n'
  + '// test/linq/contract-corpus.js (each entry\'s EMITTED document) — regenerate\n'
  + '// with `node scripts/generate-contract-pen-fixture.js`.\n'
  + '// test/linq/contract-pen.test.js fails if this drifts from what the\n'
  + '// generator produces.\n\n';

/**
 * Render the corpus as one declaration file. Exported so the test can
 * prove the committed copy is exactly this.
 * @returns {string}
 */
export function renderFixture() {
  let out = HEADER;
  for (const entry of CORPUS) {
    const projected = toTypeScript(compileContract(entry.build().document), { banner: false });
    out += `export namespace ${entry.name} {\n${projected}}\n\n`;
  }
  return out;
}

if (process.argv[1] !== undefined
  && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  const target = path.join(ROOT, 'test', 'consumer', 'linq-contract-generated.ts');
  fs.writeFileSync(target, renderFixture());
  console.log(`wrote ${path.relative(ROOT, target)}`);
}

//#endregion
