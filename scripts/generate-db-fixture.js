//#region the db entity-types fixture
// Regenerates test/consumer/db-generated.ts from the shared fixture model.
//
// Committed for the same reason emit-generated.ts is: the type half of the
// verification runs under `npm run test:types` against files on disk, and
// test/db/emit-model.test.js fails if this file drifts from what the
// generator produces — the committed copy can never become stale evidence.
import * as fs from 'fs';
import * as path from 'path';

import { compileEmitModel } from '@jarenjs/emit';
import { renderTypeScript } from '@jarenjs/emit/typescript';
import { entityEmitModel } from '@jarenjs/db';

import { FIXTURE_MODEL } from '../test/db/emit-model-fixture.js';

const ROOT = path.resolve(import.meta.dirname, '..');
const HEADER = '// Generated by @jarenjs/db entityEmitModel + @jarenjs/emit from\n'
  + '// test/db/emit-model-fixture.js — regenerate with\n'
  + '// `node scripts/generate-db-fixture.js`. test/db/emit-model.test.js\n'
  + '// fails if this drifts from what the generator produces.\n\n';

const model = entityEmitModel(FIXTURE_MODEL, {
  compile: compileEmitModel,
  source: 'test/db/emit-model-fixture.js',
});
const target = path.join(ROOT, 'test', 'consumer', 'db-generated.ts');
fs.writeFileSync(target, HEADER + renderTypeScript(model, { banner: false }));
console.log(`wrote ${path.relative(ROOT, target)}`);

//#endregion
