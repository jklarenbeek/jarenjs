#!/usr/bin/env node
//@ts-check
/**
 * Regenerate `components/md/src/entities.js` — the HTML5 named character
 * reference table CommonMark requires.
 *
 * The data is the WHATWG HTML standard's named character references
 * (§13.5, the `entities.json` the spec publishes): a fixed, normative
 * table, not an implementation's choices. It is read here from the
 * `character-entities` dev dependency, which is that table verbatim, and
 * emitted as one packed string so the shipped source carries no build
 * step and no runtime dependency.
 *
 * Run after a `character-entities` upgrade; the output is committed.
 *
 *   node scripts/generate-md-entities.js
 */

import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const module_ = require('character-entities');
const table = module_.characterEntities ?? module_;

const names = Object.keys(table).sort();
if (names.length < 2000) {
  console.error(`refusing to generate: only ${names.length} entities found`);
  process.exit(1);
}

// `name:codepoint[+codepoint]` in hex, comma separated. Hex rather than
// the character itself because a handful of references ARE whitespace
// (`NewLine`, `Tab`), which no line/space delimiter survives — and an
// all-ASCII table cannot be broken by an editor normalizing the file.
const packed = names.map((name) => {
  const points = [...table[name]].map((ch) => ch.codePointAt(0).toString(16));
  return `${name}:${points.join('+')}`;
}).join(',');

const source = `//@ts-check
/**
 * @file The HTML5 named character references, as CommonMark requires
 * them (its "entity and numeric character references" section defers to
 * the WHATWG HTML standard's table, all ${names.length} of them — a
 * pragmatic subset is a dialect, not CommonMark).
 *
 * GENERATED by \`scripts/generate-md-entities.js\`; do not edit by hand.
 *
 * The table is packed as one string and split on first use rather than
 * written as ${names.length} object properties: the packed form is a
 * quarter of the source bytes and one allocation, and a document with no
 * entity in it never pays for the Map at all.
 */

/** \`name:codepoint[+codepoint]\` (hex), comma separated. */
const PACKED = ${JSON.stringify(packed)};

/** @type {Map<string, string>|null} */
let table = null;

/**
 * The named character reference table, built on first use.
 * @returns {Map<string, string>}
 */
export function namedEntities() {
  if (table === null) {
    table = new Map();
    for (const entry of PACKED.split(',')) {
      const at = entry.indexOf(':');
      table.set(entry.slice(0, at), String.fromCodePoint(
        ...entry.slice(at + 1).split('+').map((hex) => parseInt(hex, 16))));
    }
  }
  return table;
}
`;

const out = new URL('../components/md/src/entities.js', import.meta.url);
writeFileSync(out, source);
console.log(`wrote ${names.length} entities (${Math.round(source.length / 1024)} kB) to ${out.pathname}`);
