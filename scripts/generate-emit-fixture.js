//#region the emit agreement fixture
// Regenerates test/consumer/emit-generated.ts from the shared corpus.
//
// The fixture is committed because the TYPE half of the cyclic verification
// runs under `npm run test:types`, which type-checks files on disk. A node
// test (test/emit/agreement.test.js) fails if this file drifts from what the
// generator produces, so the committed copy can never become stale evidence.
import * as fs from 'fs';
import * as path from 'path';

import { emitTypeScript } from '@jarenjs/emit/typescript';

import { CORPUS } from '../test/emit/corpus.js';

const ROOT = path.resolve(import.meta.dirname, '..');
const HEADER = '// Generated by @jarenjs/emit from test/emit/corpus.js — regenerate with\n'
  + '// `node scripts/generate-emit-fixture.js`. test/emit/agreement.test.js\n'
  + '// fails if this drifts from what the generator produces.\n\n';

let out = HEADER;
for (const entry of CORPUS)
  out += emitTypeScript(entry.schema, { name: entry.name, banner: false });

const target = path.join(ROOT, 'test', 'consumer', 'emit-generated.ts');
fs.writeFileSync(target, out);
console.log(`wrote ${path.relative(ROOT, target)}`);

//#endregion
