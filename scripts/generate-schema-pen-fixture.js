//#region the schema-pen agreement fixture
// Regenerates test/consumer/linq-schema-generated.ts from the schema-pen
// corpus: emit's declarations for every entry's EMITTED document (the pen
// builds it; nothing here is hand-written), under the entry's normalize
// profile where it carries one.
//
// The fixture is committed because the TYPE half of the three-way
// agreement runs under `npm run test:types`, which type-checks files on
// disk; test/linq/schema-pen.test.js fails if this file drifts from what
// the generator produces, so the committed copy can never become stale
// evidence.
//
// One convention rides on top of emit's reading, the same one
// `@jarenjs/db`'s entity types use: a string with `format: 'date-time'` or
// `format: 'date'` is the `DateTime` brand (structurally the linq brand),
// so the linq date operators light up on a chain over a pen's shape.
// Emit itself reads a format as a dropped constraint, so the brand is
// applied by rewriting those nodes to a `$ref` of one shared `DateTime`
// definition before emit reads the document — in every position, an
// array item as much as a member — and the definition's declaration is
// then the brand intersection rather than `string`.
import * as fs from 'fs';
import * as path from 'path';

import { compileEmitModel } from '@jarenjs/emit/model';
import { renderTypeScript } from '@jarenjs/emit/typescript';

import { CORPUS } from '../test/linq/schema-corpus.js';

const ROOT = path.resolve(import.meta.dirname, '..');
export const HEADER = '// Generated by @jarenjs/emit from test/linq/schema-corpus.js (each entry\'s\n'
  + '// EMITTED document) — regenerate with\n'
  + '// `node scripts/generate-schema-pen-fixture.js`. test/linq/schema-pen.test.js\n'
  + '// fails if this drifts from what the generator produces.\n\n';

const DATE_FORMATS = ['date-time', 'date'];
const DATE_TIME_REF = '#/$defs/DateTime';

/** Rewrite date-formatted string nodes to the shared brand definition. */
function brandDates(node) {
  if (Array.isArray(node)) return node.map(brandDates);
  if (node === null || typeof node !== 'object') return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) out[key] = brandDates(value);
  if (!DATE_FORMATS.includes(out.format)) return out;
  if (out.type === 'string') {
    delete out.type;
    delete out.format;
    return { $ref: DATE_TIME_REF, ...out };
  }
  if (Array.isArray(out.type) && out.type.length === 2 && out.type.includes('string')
    && out.type.includes('null')) {
    delete out.type;
    delete out.format;
    return { anyOf: [{ $ref: DATE_TIME_REF }, { type: 'null' }], ...out };
  }
  return out;
}

/** The brand declaration, structurally `@jarenjs/linq`'s `DateTime`. */
function brandDeclaration(model) {
  const declaration = model.declarations.find((d) => d.name === 'DateTime');
  if (declaration === undefined) return model;
  declaration.type = {
    kind: 'intersection',
    parts: [{ kind: 'primitive', primitive: 'string' }, {
      kind: 'object',
      members: [{
        kind: 'member', name: '__jarenTag',
        type: { kind: 'literal', value: 'date-time' }, required: true,
        constraints: [], doc: [],
      }],
    }],
  };
  declaration.doc = ['An RFC 3339 string branded for the date operators;',
    'structurally identical to the @jarenjs/linq brand.'];
  return model;
}

/** Whether a document reaches a date-formatted string anywhere. */
function usesDates(node) {
  if (Array.isArray(node)) return node.some(usesDates);
  if (node === null || typeof node !== 'object') return false;
  if (DATE_FORMATS.includes(node.format)) return true;
  return Object.values(node).some(usesDates);
}

/**
 * Render the corpus as one declaration file. Exported so the test can
 * prove the committed copy is exactly this.
 * @returns {string}
 */
export function renderFixture() {
  let out = HEADER;
  let dated = false;
  const reserved = [];
  for (const entry of CORPUS) {
    let schema = entry.build().schema;
    if (typeof schema === 'object' && usesDates(schema)) {
      if (schema.$defs?.DateTime !== undefined) {
        throw new Error(`${entry.name}: a definition named DateTime collides with the brand`);
      }
      const branded = brandDates(schema);
      schema = { $defs: { DateTime: { type: 'string' }, ...(branded.$defs ?? {}) }, ...branded };
      delete schema.$defs.DateTime;
      schema.$defs = { DateTime: { type: 'string' }, ...schema.$defs };
    }
    const model = compileEmitModel(schema, {
      name: entry.name, normalize: entry.normalize ?? null,
      reserved: reserved.slice(),
    });
    for (const declaration of model.declarations) {
      if (declaration.name === 'DateTime') {
        if (dated) {
          // one brand for the whole file: later entries reference the
          // first declaration
          model.declarations.splice(model.declarations.indexOf(declaration), 1);
          continue;
        }
        dated = true;
        brandDeclaration(model);
      }
      if (declaration.name !== 'DateTime') reserved.push(declaration.name);
    }
    out += renderTypeScript(model, { banner: false });
  }
  return out;
}

if (process.argv[1] !== undefined
  && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  const target = path.join(ROOT, 'test', 'consumer', 'linq-schema-generated.ts');
  fs.writeFileSync(target, renderFixture());
  console.log(`wrote ${path.relative(ROOT, target)}`);
}

