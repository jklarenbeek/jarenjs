/**
 * An engine's fixture: a database holding the given tables, a store driver
 * and a migration target over it, and a raw SQL writer outside the store.
 * An engine that reviews a migration against a complete target catalog
 * supplies `review`: the catalog its steps would leave behind.
 * @typedef {{ dialect: any, driver: any, target: any, exec: (sql: string) => Promise<void>,
 *   all: (sql: string) => Promise<Record<string, any>[]>, source: () => Promise<any[]>,
 *   connection: () => Promise<any>, review?: (steps: any[]) => Promise<any>,
 *   dispose: () => Promise<void> }} RuleFixture
 * @typedef {{ name: string, fixture: (tables: Record<string, string>) => Promise<RuleFixture> }} RuleEngine
 */

/** The SQLite engine: one in-memory database the store and the raw writer share.
 * @returns {RuleEngine} */
export function sqliteEngine() {
  return { name: 'sqlite', async fixture(tables) {
    const connection = await nodeDriver().open(':memory:');
    connection.exec(tables.sqlite);
    let open = true;
    return {
      dialect: sqliteDialect,
      // the store owns the handle it is given: a refused open closes it
      driver: { ...nodeDriver(), open: async () => { open = false; return connection; } },
      target: { driver: { ...nodeDriver(), open: async () => ({ ...connection, close() {} }) } },
      exec: async (sql) => { connection.exec(sql); },
      all: async (sql) => connection.prepare(sql).all([]),
      source: async () => (await readSchema(connection)).objects,
      connection: async () => connection,
      dispose: async () => { if (open) connection.close(); },
    };
  } };
}

const url = process.env.JAREN_PG_URL;
let fixtures = 0;
/** The PostgreSQL engine: a schema of its own on the server `JAREN_PG_URL` names, dropped by `dispose`.
 * @returns {RuleEngine} */
export function postgresEngine() {
  return { name: 'postgres', async fixture(tables) {
    const { default: pg } = await import('pg');
    const schema = `jaren_rules_${process.pid}_${++fixtures}`;
    // two pooled sessions and the fixture's own: three at most
    const pool = new pg.Pool({ connectionString: url, max: 2 });
    const client = new pg.Client({ connectionString: url });
    await client.connect();
    try { await client.query(`CREATE SCHEMA "${schema}"; SET search_path TO "${schema}"; ${tables.postgres}`); }
    catch (error) { await client.end(); await pool.end(); throw error; }
    const driver = postgresDriver(pool, { schema });
    /** @type {any} */
    let connection;
    const open = async () => (connection ??= await driver.open());
    return {
      dialect: postgresDialect({ searchPath: schema }),
      driver, target: { driver },
      exec: async (sql) => { await client.query(sql); },
      all: async (sql) => (await client.query(sql)).rows,
      source: async () => (await readSchema(await open())).catalog,
      connection: open,
      // the reviewed target: what the steps leave behind, read inside a transaction that is rolled back
      review: async (steps) => {
        let target;
        await assert.rejects((await open()).transaction(async (/** @type {any} */ tx) => {
          for (const step of steps) await tx.exec(step.sql);
          target = { dialect: 'postgres', schema, catalog: (await readSchema(tx)).catalog };
          throw new Error('review only');
        }), /review only/);
        return target;
      },
      dispose: async () => {
        try { await connection?.close(); await client.query(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`); }
        finally { await client.end(); await pool.end(); }
      },
    };
  } };
}

/**
 * The scenario. Returns what the tables hold at its end, so two installs and
 * two engines can be compared row for row.
 * @param {RuleEngine} engine @param {boolean} upgraded @returns {Promise<string>}
 */
export async function ruleLifecycle(engine, upgraded) {
  const prepare = async () => {
    const fixture = await engine.fixture(RULE_TABLES);
    if (upgraded) await fixture.exec("INSERT INTO entry VALUES(20, 1, 2, 'draft'); DELETE FROM entry");
    return fixture;
  };
  const refused = await prepare();
  try { await assert.rejects(openStore(ruleModel, { driver: refused.driver }), { code: 'JD0002' }); }
  finally { await refused.dispose(); }
  const fixture = await prepare();
  try {
    const statements = planInvariants(ruleModel, { dialect: fixture.dialect });
    if (upgraded) {
      const from = structuredClone(ruleModel);
      from.entities.Entry.invariants = [];
      const source = await fixture.source();
      const steps = statements.map((statement) => ({ kind: 'ddl', sql: statement.sql }));
      const physicalTarget = await fixture.review?.(steps);
      const migration = await planPhysicalMigration(await fixture.connection(), from, ruleModel, {
        id: 'install-rules', steps, ...(physicalTarget === undefined ? {} : { physicalTarget }),
        dispositions: Object.fromEntries(source.map((object) => [physicalObjectKey(object), 'preserve'])),
        assertions: [{ sql: 'SELECT * FROM entry', expected: [] }],
      });
      // a reviewed target catalog is the whole acceptance where there is one;
      // the model's stored-row walk reads SQLite tables only
      const options = { baseline: from, shadow: false, ...(physicalTarget === undefined ? { model: ruleModel } : {}) };
      await migrate(fixture.target, [migration], options);
      assert.equal((await migrate(fixture.target, [migration], options)).applied.length, 0);
    }
    else for (const statement of statements) await fixture.exec(statement.sql);
    const count = async () => Number((await fixture.all('SELECT count(*) AS n FROM audit'))[0].n);
    const store = await openStore(ruleModel, { driver: fixture.driver, adopt: true });
    try {
      const created = await store.entity('Entry').create({ start: 1, end: 2, phase: 'draft' });
      assert.equal(created.id, 1);
      await assert.rejects(store.entity('Entry').update(1, { start: 3 }), { code: 'JD2096', class: 'constraint' });
      store.entity('Entry').put({ ...created, start: 3 });
      await assert.rejects(store.saveChanges(), { code: 'JD2096', class: 'constraint' });
      store.entity('Entry').discard(1);
      const native = { op: 'update', key: 1, set: { start: 0 } };
      await assert.rejects(store.entity('Entry').mutate({ ...native, set: { start: 3 } }), { code: 'JD2096', class: 'constraint' });
      assert.equal((await store.entity('Entry').mutate(native)).affected, 1);
      const nativeAudit = await count();
      assert.equal((await store.entity('Entry').mutate(native)).affected, 0);
      assert.equal(await count(), nativeAudit);
      for (const sql of ["INSERT INTO entry(starts,ends,phase) VALUES(3,2,'draft')", 'UPDATE entry SET starts=NULL WHERE id=1'])
        await assert.rejects(fixture.exec(sql), (e) => classifyDriverError(e).class === 'constraint');
      await store.entity('Entry').update(1, { phase: 'frozen' });
      const before = await count();
      await store.entity('Entry').update(1, { phase: 'frozen' });
      await fixture.exec("UPDATE entry SET phase='frozen' WHERE id=1");
      assert.equal(await count(), before);
      await assert.rejects(store.entity('Entry').delete(1), { code: 'JD2096' });
      await assert.rejects(fixture.exec('DELETE FROM entry WHERE id=1'), /jaren invariant:frozen/);
      return JSON.stringify({ rows: await fixture.all('SELECT * FROM entry ORDER BY id'), audit: await fixture.all('SELECT * FROM audit ORDER BY id') });
    }
    finally { await store.close(); }
  }
  finally { await fixture.dispose(); }
}

/** Two nullable integers, for the query engine's null truth tables. */
export const truthModel = { $model: '0.1', entities: { Row: { schema: { type: 'object', properties: {
  id: { type: 'integer', 'x-entity': { key: true } }, a: { type: ['integer', 'null'] }, b: { type: ['integer', 'null'] },
} }, physical: { table: 'rows', columns: { id: column('id'), a: column('a', 'integer', 'null'), b: column('b', 'integer', 'null') } } } } };
const TRUTH_TABLES = {
  sqlite: 'CREATE TABLE rows(id INTEGER PRIMARY KEY, a INTEGER, b INTEGER)',
  postgres: 'CREATE TABLE rows(id integer PRIMARY KEY, a bigint, b bigint)',
};
/** A value its codec cannot read: text in an integer column, an integer past the safe range. */
const TRUTH_WRONG_STORAGE = { sqlite: "INSERT INTO rows VALUES(1, 'wrong type', 4)", postgres: 'INSERT INTO rows VALUES(1, 9007199254740993, 4)' };
export const TRUTH_PREDICATES = [{ $eq: ['$.new.a', '$.new.b'] }, { $ne: ['$.new.a', { $const: null }] },
  { $le: ['$.new.a', '$.new.b'] }, { $not: { $lt: ['$.new.a', '$.new.b'] } },
  { $and: [{ $eq: ['$.op', 'insert'] }, { $or: [{ $gt: ['$.new.a', 0] }, { $eq: ['$.new.a', null] }] }] },
  // a missing member compares false with anything, a different type included
  { $ne: ['$.new.a', '$.new.b'] }, { $ne: ['$.new.a', 2] }, { $ne: ['$.new.a', 'x'] },
  // membership in a list of literals (a null item matches a null), existence, and each negated
  { $eq: ['$.new.a', { $seq: [-1, 0] }] }, { $eq: ['$.new.a', { $seq: [2, null] }] }, { $exists: '$.new.a' },
  { $not: { $eq: ['$.new.a', { $seq: [-1, 0] }] } }, { $not: { $eq: ['$.new.a', { $seq: [2, null] }] } }, { $not: { $exists: '$.new.a' } },
  { $and: [{ $exists: '$.new.a' }, { $eq: ['$.new.b', { $seq: [null, -1] }] }] },
  { $or: [{ $eq: ['$.new.b', { $seq: [null] }] }, { $lt: ['$.new.a', 0] }] },
  // integer arithmetic: a missing operand leaves it without a value, so its comparison is false, as the engine answers;
  // over a column whose SQL NULL is a JSON null it refuses at planning (a null is no number to the engine)
  { $le: [{ $add: ['$.new.a', 1] }, '$.new.b'] }, { $eq: [{ $sub: ['$.new.b', '$.new.a'] }, 3] }, { $gt: [{ $neg: '$.new.a' }, 0] },
  { $ne: [{ $add: ['$.new.a', '$.new.b'] }, 1] }, { $not: { $lt: [{ $add: [{ $neg: '$.new.a' }, { $const: 2 }] }, '$.new.b'] } },
  { $or: [{ $not: { $exists: '$.new.a' } }, { $eq: [{ $add: ['$.new.a', 1] }, '$.new.b'] }] },
  // a negated negative literal installs (its rendering must not open a SQL comment)
  { $gt: ['$.new.a', { $neg: -1 }] }];

/** The `null` policy of each truth column: SQL NULL is a JSON null, or an
 * absent member in both columns, or in `a` beside a `b` that holds null. */
export const TRUTH_POLICIES = { null: { a: 'null', b: 'null' }, absent: { a: 'absent', b: 'absent' }, mixed: { a: 'absent', b: 'null' } };

/** Whether an expression compares a member its column reads as absent with a
 * `null` literal or a list holding one: a plan refuses it, since such a member
 * never holds null. @param {any} node @param {string[]} absent @returns {boolean} */
function nullOfAbsent(node, absent) {
  if (!node || typeof node !== 'object') return false;
  if (Array.isArray(node)) return node.some((item) => nullOfAbsent(item, absent));
  const isNull = (/** @type {any} */ value) => value === null || value?.$const === null;
  return Object.entries(node).some(([key, args]) => (['$eq', '$ne', '$lt', '$le', '$gt', '$ge'].includes(key) && Array.isArray(args)
    && args.some((arg) => absent.some((name) => arg === `$.new.${name}`))
    && args.some((arg) => isNull(arg) || (Array.isArray(arg?.$seq) && arg.$seq.some(isNull))))
    || nullOfAbsent(args, absent));
}

/** Whether an expression's arithmetic reads a member whose column reads SQL
 * NULL as a JSON null: a plan refuses it, since the engine's arithmetic over a
 * null is a type error, not a verdict. @param {any} node @param {string[]} nulls @returns {boolean} */
function arithmeticOverNull(node, nulls) {
  if (!node || typeof node !== 'object') return false;
  if (Array.isArray(node)) return node.some((item) => arithmeticOverNull(item, nulls));
  return Object.entries(node).some(([key, args]) => (['$add', '$sub', '$neg'].includes(key)
    && [args].flat().some((arg) => nulls.some((name) => arg === `$.new.${name}`))) || arithmeticOverNull(args, nulls));
}

/** The reason a plan refuses an expression over columns of the given `null`
 * policies, or `null` where it plans. @param {any} node @param {Record<string, string>} policy */
function plannedRefusal(node, policy) {
  const of = (/** @type {string} */ wanted) => Object.keys(policy).filter((name) => policy[name] === wanted);
  return nullOfAbsent(node, of('absent')) ? /never holds null/ : arithmeticOverNull(node, of('null')) ? /no number/ : null;
}

/**
 * Every truth predicate over `{ null, -1, 2 }²`: the trigger accepts exactly
 * what the query engine accepts over the record as stored — a member omitted
 * where its column reads SQL NULL as absent — and refuses a row its codec
 * cannot read; a plan refuses a `null` literal against an absent member.
 * @param {RuleEngine} engine @param {{ a: string, b: string }} [policy] the columns' `null` policies
 * @returns {Promise<string>} per predicate, its verdicts or `refused`
 */
export async function ruleTruthTable(engine, policy = TRUTH_POLICIES.null) {
  const verdicts = [];
  const absent = Object.keys(policy).filter((name) => policy[/** @type {'a' | 'b'} */ (name)] === 'absent');
  for (const expression of TRUTH_PREDICATES) {
    const spec = /** @type {any} */ (structuredClone(truthModel));
    for (const name of ['a', 'b']) spec.entities.Row.physical.columns[name].null = policy[/** @type {'a' | 'b'} */ (name)];
    spec.entities.Row.invariants = [{ name: 'truth', on: ['insert'], assert: expression, enforcement: 'database' }];
    const evaluate = compileJsonQuery(expression);
    const fixture = await engine.fixture(TRUTH_TABLES);
    try {
      const refusal = plannedRefusal(expression, policy);
      if (refusal !== null) {
        assert.throws(() => planInvariants(spec, { dialect: fixture.dialect }), { code: 'JD0005', message: refusal }, JSON.stringify(expression));
        verdicts.push('refused');
        continue;
      }
      for (const statement of planInvariants(spec, { dialect: fixture.dialect })) await fixture.exec(statement.sql);
      const row = [];
      for (const a of [null, -1, 2]) for (const b of [null, -1, 2]) {
        const insert = () => fixture.exec(`INSERT INTO rows VALUES(1, ${a}, ${b})`);
        const stored = Object.fromEntries(Object.entries({ a, b }).filter(([name, value]) => value !== null || !absent.includes(name)));
        const accepted = evaluate({ old: null, new: { id: 1, ...stored }, op: 'insert' }) === true;
        if (accepted) { await insert(); await fixture.exec('DELETE FROM rows'); }
        else await assert.rejects(insert(), /jaren invariant:truth/, `${JSON.stringify(expression)} over ${JSON.stringify(stored)}`);
        row.push(accepted);
      }
      verdicts.push(row);
      await assert.rejects(fixture.exec(TRUTH_WRONG_STORAGE[engine.name]), /jaren invariant:truth/);
    }
    finally { await fixture.dispose(); }
  }
  return JSON.stringify(verdicts);
}

