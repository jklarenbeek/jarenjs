/** What a write came to: `ok`, or the rule that refused it, whoever enforced it.
 * @param {() => any} write @returns {Promise<string>} */
async function outcome(write) {
  try { await write(); return 'ok'; }
  catch (error) {
    const message = String(/** @type {any} */ (error)?.message);
    const rule = /jaren invariant:(\w+)/.exec(message)?.[1] ?? /persistence invariant '(\w+)'/.exec(message)?.[1];
    if (rule === undefined) throw error;
    return `refused ${rule}`;
  }
}

/**
 * The families' scenario: the store's writes (create, update, a no-op, a
 * tracked save, delete), then — where the database enforces — raw SQL that
 * assigns without changing and sets a revision itself. Returns every outcome
 * and the rows left behind.
 * @param {RuleEngine} engine @param {{ enforcement: 'database' | 'store', upgraded: boolean }} options
 * @returns {Promise<string>}
 */
export async function familyLifecycle(engine, { enforcement, upgraded }) {
  const model = familyModel(enforcement);
  const fixture = await engine.fixture(FAMILY_TABLES);
  try {
    const statements = planInvariants(model, { dialect: fixture.dialect });
    if (upgraded) {
      const from = structuredClone(model);
      from.entities.Line.invariants = [];
      const source = await fixture.source();
      const steps = statements.map((statement) => ({ kind: 'ddl', sql: statement.sql }));
      const physicalTarget = await fixture.review?.(steps);
      const migration = await planPhysicalMigration(await fixture.connection(), from, model, {
        id: 'install-families', steps, ...(physicalTarget === undefined ? {} : { physicalTarget }),
        dispositions: Object.fromEntries(source.map((object) => [physicalObjectKey(object), 'preserve'])), assertions: [],
      });
      await migrate(fixture.target, [migration], { baseline: from, shadow: false, ...(physicalTarget === undefined ? { model } : {}) });
    }
    else for (const statement of statements) await fixture.exec(statement.sql);
    const store = await openStore(model, { driver: fixture.driver });
    try {
      const writes = [], raw = [], rows = [];
      const snapshot = async () => { rows.push(await fixture.all('SELECT * FROM lines ORDER BY id')); };
      const docs = store.entity('Doc'), lines = store.entity('Line');
      await docs.create({ id: 1, status: 'draft', sealed: null, code: 'c1' });
      await docs.create({ id: 2, status: 'final', sealed: null });
      await docs.create({ id: 3, status: 'draft', sealed: '2020-01-01' });
      // a parent that is a draft, unsealed and present, or no insert; one named by
      // its code, and one by a code no parent has. Keys are explicit: a refused
      // insert spends a PostgreSQL identity value, not a rowid
      for (const [id, doc, code] of [[1, 1, 'c1'], [2, 2], [3, 3], [4, 9], [2, 1], [7, 1, 'zz']])
        writes.push(await outcome(() => lines.create({ id, doc, qty: 1, note: 'a', revision: 0, ...(code === undefined ? {} : { code }) })));
      // a no-op writes nothing; the parent column is pinned; a locked line takes no write
      for (const changes of [{ qty: 2 }, { qty: 2 }, { doc: 2 }, { note: 'locked' }, { qty: 3 }])
        writes.push(await outcome(() => lines.update(1, changes)));
      lines.put({ ...(await lines.get(2)), qty: 9 });
      writes.push(await outcome(() => store.saveChanges()));
      lines.put({ ...(await lines.get(2)), doc: 3 });
      writes.push(await outcome(() => store.saveChanges()));
      lines.discard(2);
      await snapshot();
      // a memo names a parent that exists, written directly or tracked
      const memos = store.entity('Memo');
      for (const [id, parent] of [['a', 2], ['b', 9]]) writes.push(await outcome(() => memos.create({ id, parent })));
      for (const [id, parent] of [['c', 9], ['d', 3]]) {
        memos.add({ id, parent });
        writes.push(await outcome(() => store.saveChanges()));
        memos.discard(id);
      }
      // a line leaves a draft parent, or one that is gone; tracked or directly
      lines.remove(2);
      writes.push(await outcome(() => store.saveChanges()));
      await docs.update(1, { status: 'final' });
      writes.push(await outcome(() => lines.delete(1)));
      lines.remove(1);
      writes.push(await outcome(() => store.saveChanges()));
      lines.discard(1);
      await docs.delete(1);
      writes.push(await outcome(() => lines.delete(1)));
      rows.push(await fixture.all('SELECT id, doc_id FROM lines ORDER BY id'));
      if (enforcement === 'database') {
        await fixture.exec("INSERT INTO docs(id, status, sealed) VALUES (4, 'draft', NULL)");
        await fixture.exec("INSERT INTO lines(id, doc_id, qty, note, revision) VALUES (3, 4, 1, 'c', 0)");
        for (const sql of ['UPDATE lines SET qty = qty + 1 WHERE id = 3', 'UPDATE lines SET qty = qty WHERE id = 3',
          'UPDATE lines SET doc_id = doc_id WHERE id = 3', 'UPDATE lines SET qty = qty + 1, revision = 10 WHERE id = 3',
          "UPDATE lines SET note = 'locked' WHERE id = 3", 'UPDATE lines SET qty = qty WHERE id = 3',
          "INSERT INTO lines(doc_id, qty, note, revision) VALUES (9, 1, 'x', 0)",
          "INSERT INTO lines(doc_id, qty, note, revision, code) VALUES (4, 1, 'y', 0, 'zz')"]) {
          raw.push(await outcome(() => fixture.exec(sql)));
          await snapshot();
        }
        raw.push(await outcome(() => fixture.exec('DELETE FROM lines WHERE id = 3')));
      }
      return JSON.stringify({ writes, raw, rows, docs: await fixture.all('SELECT * FROM docs ORDER BY id'),
        lines: await fixture.all('SELECT * FROM lines ORDER BY id') });
    }
    finally { await store.close(); }
  }
  finally { await fixture.dispose(); }
}

